 await p.goto('file://'+__dirname.replace(/\\/g,'/')+'/rev6a.html');await p.waitForTimeout(400);
 await p.evaluate(()=>setModule('cad'));
 const run=async(...cmds)=>{for(const c of cmds){await p.evaluate(c=>cadSubmit(c),c)}};
